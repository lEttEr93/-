'use strict';
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const root=path.resolve(__dirname,'..');
const dest=path.resolve(process.argv[2]||path.join(process.env.AI_ROOT||'D:\\AI','artifacts','campus-life','2026-10-20-desktop-android','out','windows'));
if(fs.existsSync(dest)&&fs.readdirSync(dest).length)throw Error('Output must be a new/empty directory: '+dest);
cp.execFileSync(process.execPath,[path.join(__dirname,'build-web.cjs')],{stdio:'inherit'});
if(!fs.existsSync(path.join(root,'build/bluetooth/CampusBluetooth.exe')))throw Error('Publish native Bluetooth helper first');
fs.mkdirSync(dest,{recursive:true});
fs.cpSync(fs.realpathSync(path.dirname(require('electron'))),dest,{recursive:true});
fs.renameSync(path.join(dest,'electron.exe'),path.join(dest,'CampusLife.exe'));
const target=path.join(dest,'resources/app');fs.mkdirSync(target,{recursive:true});
for(const name of ['desktop','shared','docs'])fs.cpSync(path.join(root,name),path.join(target,name),{recursive:true});
for(const name of ['web','bluetooth'])fs.cpSync(path.join(root,'build',name),path.join(target,'build',name),{recursive:true});
fs.mkdirSync(path.join(target,'android/assets'),{recursive:true});fs.mkdirSync(path.join(target,'android/res/mipmap-xxxhdpi'),{recursive:true});
fs.copyFileSync(path.join(root,'android/assets/index.html'),path.join(target,'android/assets/index.html'));
fs.copyFileSync(path.join(root,'android/res/mipmap-xxxhdpi/ic_launcher.png'),path.join(target,'android/res/mipmap-xxxhdpi/ic_launcher.png'));
const pkg=require('../package.json');delete pkg.devDependencies;delete pkg.scripts;fs.writeFileSync(path.join(target,'package.json'),JSON.stringify(pkg,null,2));
fs.copyFileSync(path.join(root,'docs/USER_GUIDE.md'),path.join(dest,'USER_GUIDE.md'));
fs.writeFileSync(path.join(dest,'Start-CampusLife.cmd'),'@echo off\r\ncd /d "%~dp0"\r\nstart "" "%~dp0CampusLife.exe" %*\r\n');
fs.writeFileSync(path.join(dest,'Start-Compatibility.cmd'),'@echo off\r\ncd /d "%~dp0"\r\nstart "" "%~dp0CampusLife.exe" --no-sandbox %*\r\n');
console.log('Portable Windows app: '+dest);
